#!/usr/bin/env python3
"""Build the three original DMG scores from the pinned, attributed source data."""
from pathlib import Path
import hashlib
import json
import re

ROOT=Path(__file__).resolve().parents[1]
REF=ROOT/'references/dmg/audio'
REV='b95c66859339f5523e80213de5857eefc1c7703f'
BASE=0x6f3f
NOTES={n:i+1 for i,n in enumerate(('C_','C#','D_','D#','E_','F_','F#','G_','G#','A_','A#','B_'))}

def number(s):
    return int(s[1:],16) if s.startswith('$') else int(s)

# Two passes resolve the source's section and channel pointers. This emits
# score data only; no Game Boy machine code or ROM image is used or generated.
lines=[];labels={};address=BASE
for raw in (REF/'music.asm').read_text().splitlines():
    line=raw.split(';',1)[0].strip()
    if not line or line.startswith(('INCLUDE','SECTION')):continue
    if line.endswith('::'):
        label=line[:-2];labels[label]=address
        assert address==int(label.rsplit('_',1)[1],16),(label,hex(address))
        continue
    op,*rest=line.split(None,1);args=[a.strip() for a in rest[0].split(',')] if rest else []
    size={'db':len(args),'dw':len(args)*2,'Notes':len(args)//2,'Noise':len(args),'Rest':1,'EndSection':1}[op]
    lines.append((op,args));address+=size
image=bytearray()
for op,args in lines:
    if op in ('db','dw'):
        for arg in args:
            value=labels[arg] if arg in labels else number(arg)
            image+=value.to_bytes(1 if op=='db' else 2,'little')
    elif op=='Notes':
        image+=bytes(NOTES[n]+(number(o)-2)*12 for n,o in zip(args[::2],args[1::2]))
    elif op=='Noise':image+=bytes(1+5*number(n) for n in args)
    elif op=='Rest':image.append(1)
    else:image.append(0)

def word(address):return int.from_bytes(image[address-BASE:address-BASE+2],'little')

start,end=labels['Channel2_6FFA'],labels['Channel1_7543']
data=image[start-BASE:end-BASE]
frames=[3,6,12,24,48,96,18,36,72,8,16,0]
songs=[]
for title,header in [('A-TYPE',0x6f6b),('B-TYPE',0x6f76),('C-TYPE',0x6f81)]:
    pointers=[word(header+3+i*2) for i in range(4)]
    lanes=[]
    for ch,base in enumerate(pointers):
        if not base:lanes.append([]);continue
        pointer=base;duration=0;events=[];instrument=[0,0,0];elapsed=0
        while (section:=word(pointer))!=0xffff:
            pointer+=2;at=section
            assert start<=at<end
            while True:
                value=image[at-BASE];at+=1
                if not value:break
                if value==0x9d:
                    instrument=list(image[at-BASE:at-BASE+3]);at+=3;continue
                if value&0xf0==0xa0:
                    duration=frames[value&15];continue
                assert duration and (value==1 or ch==3 or value%2==0),(title,ch,value)
                events.append([value,duration,*instrument]);elapsed+=duration
        assert word(pointer+2)==base,(title,ch,'Unexpected partial loop')
        lanes.append(events)
    lengths=[sum(e[1] for e in lane) for lane in lanes]
    assert lengths[0]==lengths[1]
    length=lengths[1]
    # Channels loop independently. In the original B score the wave lane is
    # 24 frames longer than the pulse lanes; preserve that phase drift.
    songs.append({'title':title,'channels':pointers,'length':length,'channel_lengths':lengths,'voices':lanes})
    print(title,'channel loop frames:',lengths,'full loop:',round(length*70224/4194304,3),'seconds')

source=(REF/'audio.asm').read_text()
def bytes_after(label,op):
    part=source.split(label+'::',1)[1].split('::',1)[0]
    return [number(x.strip()) for row in part.splitlines() if row.split(';',1)[0].strip().startswith(op+' ')
            for x in row.split(';',1)[0].strip()[len(op):].split(',')]
pitches=bytes_after('NotePitches','dw')
vibrato=bytes_after('VibratoOffsets','db')
waves=[bytes_after(label,'db') for label in ('WavePattern_6EA9','WavePattern_6EB9','WavePattern_6EC9','DefaultWavePattern')]
assert len(pitches)==73 and len(vibrato)==55 and all(len(w)==16 for w in waves)
noise=bytes_after('Data_6E94','db');assert len(noise)==21
h='''// Generated by tools/make_music.py. Original score data: Nintendo, 1989.
#pragma once
#include <stdint.h>
constexpr unsigned SONG_COUNT=3;
constexpr uint32_t DMG_CLOCK=4194304, DMG_FRAME_CYCLES=70224;
constexpr uint16_t DMG_MUSIC_BASE=0x6ffa;
struct Song { const char *title; uint16_t channels[4], length; };
extern const Song SONGS[SONG_COUNT];
extern const uint8_t DMG_MUSIC[], DMG_LENGTHS[12], DMG_VIBRATO[55], DMG_WAVES[4][16], DMG_NOISE[21];
extern const uint16_t DMG_PITCHES[73];
'''
out=['// Generated by tools/make_music.py. Score data only; see NOTICE.','#include "Songs.h"']
def array(kind,name,values,width=24):
    out.append(f'const {kind} {name}[{len(values)}] = {{')
    out.extend('  '+','.join(map(str,values[i:i+width]))+',' for i in range(0,len(values),width))
    out.append('};')
array('uint8_t','DMG_MUSIC',data)
array('uint8_t','DMG_LENGTHS',frames)
array('uint16_t','DMG_PITCHES',pitches)
array('uint8_t','DMG_VIBRATO',vibrato)
array('uint8_t','DMG_NOISE',noise)
out.append('const uint8_t DMG_WAVES[4][16] = {')
out.extend('  {'+','.join(map(str,w))+'},' for w in waves);out.append('};')
out.append('const Song SONGS[SONG_COUNT] = {')
for song in songs:out.append('  {"'+song['title']+'", {'+','.join(map(str,song['channels']))+'}, '+str(song['length'])+'},')
out.append('};\n')
(ROOT/'src/Songs.h').write_text(h)
(ROOT/'src/Songs.cpp').write_text('\n'.join(out))
(ROOT/'tools/music.json').write_text(json.dumps({'revision':REV,'clock':4194304,'frame_cycles':70224,
    'source':{name:{'url':f'https://raw.githubusercontent.com/kaspermeerts/tetris/{REV}/{name}',
                    'sha256':hashlib.sha256((REF/name).read_bytes()).hexdigest()}
              for name in ('music.asm','music_macros.asm','audio.asm')},'songs':songs},indent=2)+'\n')
