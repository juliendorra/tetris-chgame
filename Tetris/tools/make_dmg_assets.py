#!/usr/bin/env python3
"""Compile the attributed DMG tile atlases/maps, and reconstruct reference screens."""
from pathlib import Path
import json
import hashlib
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]
REF=ROOT/'references/dmg'
meta=json.loads((REF/'sources.json').read_text())

def tiles(name):
    assert hashlib.sha256((REF/name).read_bytes()).hexdigest()==meta['assets'][name]['sha256']
    im=Image.open(REF/name).convert('L')
    return [im.crop((x,y,x+8,y+8)) for y in range(0,im.height,8) for x in range(0,im.width,8)]

font=tiles('font.png')[:39]
title=tiles('copyrightandtitlescreen.png')
game=tiles('configandgameplay.png')
maps=json.loads((REF/'tilemaps.json').read_text())
header=['// Generated by tools/make_dmg_assets.py. Original artwork: Nintendo, 1989.',
        '// Public reference provenance and hashes: references/dmg/sources.json.',
        '#pragma once','#include <stdint.h>','namespace dmg {',
        'extern const uint8_t FONT[39][16], TITLE[128][16], GAME[208][16];']
out=['// Generated by tools/make_dmg_assets.py; see NOTICE for artwork attribution.', '#include "DmgAssets.h"','namespace dmg {']
for name,atlas in [('FONT',font),('TITLE',title),('GAME',game)]:
    out.append(f'const uint8_t {name}[{len(atlas)}][16] = {{')
    for tile in atlas:
        px=[(255-tile.getpixel((x,y)))//85 for y in range(8) for x in range(8)]
        packed=[sum(px[i+j]<<(j*2) for j in range(4)) for i in range(0,64,4)]
        out.append('  {'+','.join(map(str,packed))+'},')
    out.append('};')
for name,data in maps.items():
    assert len(data)==360
    short={'TitleScreenTilemap':'TITLE_MAP','ConfigScreenTilemap':'MENU_MAP',
           'TypeADifficultyTilemap':'LEVEL_A_MAP','TypeBDifficultyTilemap':'LEVEL_B_MAP',
           'TypeAGameplayTilemap':'PLAY_A_MAP','TypeBGameplayTilemap':'PLAY_B_MAP'}[name]
    header.append(f'extern const uint8_t {short}[360];')
    out.append(f'const uint8_t {short}[360] = {{')
    for row in range(18):out.append('  '+','.join(map(str,data[row*20:row*20+20]))+',')
    out.append('};')
    atlas=font+title if short=='TITLE_MAP' else font+title[:9]+game
    im=Image.new('L',(160,144))
    for i,index in enumerate(data):im.paste(atlas[index],((i%20)*8,(i//20)*8))
    im.save(REF/f'{name}.png')
header+=['}',''];out+=['}','']
(ROOT/'src/DmgAssets.h').write_text('\n'.join(header))
(ROOT/'src/DmgAssets.cpp').write_text('\n'.join(out))
print('DMG assets: 375 tiles, six screen maps; reference screens reconstructed at 160x144')
